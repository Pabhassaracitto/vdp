"""Myanmar (`my`) extensions for the Nhân Duyên / Paṭiccasamuppāda tables.

WHY A SEPARATE MODULE
---------------------
`data_priority_conditions.py` stores one flat tuple per locale
(`(name, shortName, definition)`), and `build_full_catalogs.py` unpacks that
tuple positionally for *every* priority language. Adding elements there would
change the arity for all seven locales at once. This module therefore holds the
`my`-only *additional* fields in parallel dicts, leaving every other locale and
every existing table untouched.

Scope is limited to fields the app actually reads
(`lib/core/localization/localized_content.dart`):

* paticcas   — characteristic, function, manifestation, proximateCause,
               doctrinalNote, examples
* paccayas   — paccayaDhamma, paccayuppanna, doctrinalNote, examples,
               subdivisions (nested map keyed by the invariant Pāḷi name)
* vithis     — arisingCondition, significance, doctrinalNote and the
               per-step name / description / doctrinalNote

Rupas and kammas are deliberately absent: their four-aspect and doctrinal-note
fields have no localization call site, so translating them would ship text no
screen can display. See `l10n_work/my_terminology_evidence.md`.

Terminology follows `l10n_work/glossary.csv` column `my` (Myanmar let-than
manual tradition, *Abhidhammattha Saṅgaha* baseline) and the Pāḷi canon
cited by each entity's `sourceRefs`.
"""

